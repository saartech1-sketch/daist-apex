CREATE TABLE DAISY_USER_LIBRARY (
    LIBRARY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_NAME VARCHAR2(255 CHAR) NOT NULL,
    ENTRY_NAME VARCHAR2(128 CHAR) NOT NULL,
    ENTRY_KIND VARCHAR2(8 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    SOURCE_CODE CLOB NOT NULL,
    LLM_PROMPT CLOB,
    IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT DUL_PK PRIMARY KEY (LIBRARY_ID),
    CONSTRAINT DUL_UQ_USER_ENTRY UNIQUE (USER_NAME, ENTRY_NAME),
    CONSTRAINT DUL_CK_KIND CHECK (ENTRY_KIND IN ('ACTION', 'VARIABLE')),
    CONSTRAINT DUL_CK_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

COMMENT ON TABLE DAISY_USER_LIBRARY IS
    'User-owned JavaScript functions (actions) and variables for Daisy.';

COMMENT ON COLUMN DAISY_USER_LIBRARY.USER_NAME IS
    'APEX application username (APP_USER) that owns this library entry.';

COMMENT ON COLUMN DAISY_USER_LIBRARY.LLM_PROMPT IS
    'LLM prompt used to generate or last edit this library entry.';

COMMENT ON COLUMN DAISY_USER_LIBRARY.IS_ACTIVE IS
    'Whether the function or variable is enabled for simulation execution.';


